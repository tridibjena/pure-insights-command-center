/* =============================================================================
   00 · Bootstrap the simulated ACCOUNT_USAGE logs in a real Snowflake account
   -----------------------------------------------------------------------------
   SNOWFLAKE-ONLY script (PostgreSQL loads the same data via the Python pipeline).

   Prerequisite: `npm run pipeline` (or `python -m pic_pipeline.cli export`) writes
   data/simulated/*.csv. Upload them with SnowSQL PUT (commands below), then run.

   Scripts 01-09 reference unqualified schemas ACCOUNT_USAGE, PORTAL and COST, so
   they run unchanged inside PURE_INSIGHTS_SIM. To run against your *live* account
   instead, replace step 3 with views over SNOWFLAKE.ACCOUNT_USAGE (see README).
   ============================================================================= */

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS PURE_INSIGHTS_SIM;
USE DATABASE PURE_INSIGHTS_SIM;
CREATE SCHEMA IF NOT EXISTS ACCOUNT_USAGE;
CREATE SCHEMA IF NOT EXISTS PORTAL;
CREATE SCHEMA IF NOT EXISTS COST;
ALTER SESSION SET TIMEZONE = 'UTC';

-- 1 · File format + stage ------------------------------------------------------
CREATE OR REPLACE FILE FORMAT PORTAL.PIC_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE;
CREATE OR REPLACE STAGE PORTAL.PIC_STAGE FILE_FORMAT = PORTAL.PIC_CSV;

-- From SnowSQL, in the repository root:
--   PUT file://data/simulated/*.csv @PURE_INSIGHTS_SIM.PORTAL.PIC_STAGE AUTO_COMPRESS=TRUE;

-- 2 · Tables (Snowflake column names; subset of the documented views) ------------
CREATE OR REPLACE TABLE ACCOUNT_USAGE.QUERY_HISTORY (
  QUERY_ID VARCHAR, QUERY_TEXT VARCHAR, DATABASE_NAME VARCHAR, SCHEMA_NAME VARCHAR,
  QUERY_TYPE VARCHAR, SESSION_ID NUMBER, USER_NAME VARCHAR, ROLE_NAME VARCHAR,
  WAREHOUSE_ID NUMBER, WAREHOUSE_NAME VARCHAR, WAREHOUSE_SIZE VARCHAR, WAREHOUSE_TYPE VARCHAR,
  QUERY_TAG VARCHAR, EXECUTION_STATUS VARCHAR, ERROR_CODE VARCHAR, ERROR_MESSAGE VARCHAR,
  START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ, TOTAL_ELAPSED_TIME NUMBER,
  COMPILATION_TIME NUMBER, EXECUTION_TIME NUMBER, QUEUED_OVERLOAD_TIME NUMBER,
  BYTES_SCANNED NUMBER, ROWS_PRODUCED NUMBER, CREDITS_USED_CLOUD_SERVICES NUMBER(38,9));

CREATE OR REPLACE TABLE ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY (
  QUERY_ID VARCHAR, PARENT_QUERY_ID VARCHAR, ROOT_QUERY_ID VARCHAR, WAREHOUSE_ID NUMBER,
  WAREHOUSE_NAME VARCHAR, QUERY_HASH VARCHAR, QUERY_PARAMETERIZED_HASH VARCHAR, QUERY_TAG VARCHAR,
  USER_NAME VARCHAR, START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ,
  CREDITS_ATTRIBUTED_COMPUTE NUMBER(38,9), CREDITS_USED_QUERY_ACCELERATION NUMBER(38,9));

CREATE OR REPLACE TABLE ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY (
  START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ, WAREHOUSE_ID NUMBER, WAREHOUSE_NAME VARCHAR,
  CREDITS_USED NUMBER(38,9), CREDITS_USED_COMPUTE NUMBER(38,9),
  CREDITS_USED_CLOUD_SERVICES NUMBER(38,9), CREDITS_ATTRIBUTED_COMPUTE_QUERIES NUMBER(38,9));

CREATE OR REPLACE TABLE PORTAL.REPORT_USAGE_MONTHLY (
  REPORT_ID VARCHAR, REPORT_NAME VARCHAR, PERIOD_MONTH DATE, SNAPSHOT_SEQ NUMBER,
  OWNER_EMAIL VARCHAR, REFRESH_STATUS VARCHAR, AVG_LOAD_TIME_SEC NUMBER(8,2),
  MONTHLY_ACTIVE_VIEWS NUMBER, CONCURRENT_USER_PEAK NUMBER, QUERY_COUNT_LAST_30D NUMBER,
  AWS_HOSTING_COST_USD NUMBER(12,2), SNOWFLAKE_CREDITS_REPORTED NUMBER(12,2));

CREATE OR REPLACE TABLE PORTAL.CREDIT_PRICING (
  PRICING_ID NUMBER, CURRENCY VARCHAR, CREDIT_PRICE_USD NUMBER(10,4));

-- 3 · Load ------------------------------------------------------------------------
COPY INTO ACCOUNT_USAGE.QUERY_HISTORY              FROM @PORTAL.PIC_STAGE/query_history.csv.gz;
COPY INTO ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY  FROM @PORTAL.PIC_STAGE/query_attribution_history.csv.gz;
COPY INTO ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY FROM @PORTAL.PIC_STAGE/warehouse_metering_history.csv.gz;
COPY INTO PORTAL.REPORT_USAGE_MONTHLY              FROM @PORTAL.PIC_STAGE/portal_report_usage_monthly.csv.gz;
COPY INTO PORTAL.CREDIT_PRICING                    FROM @PORTAL.PIC_STAGE/portal_credit_pricing.csv.gz;
